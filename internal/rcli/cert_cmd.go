	fl.StringVar(&locality, "locality", "", "subject locality (L)")
	fl.StringSliceVar(&sans, "san", nil, "subject alternative name (repeatable)")
	fl.StringVar(&keyType, "key-type", "", "key algorithm")
	fl.StringVar(&profile, "profile", "", "server|client|server-client|code-signing|email")
	fl.IntVar(&days, "days", 0, "validity in days")
	fl.StringVar(&outDir, "out", "", "write cert, key and chains into this directory")
	fl.BoolVar(&noStoreKey, "no-store-key", false, "do not retain the key server-side (download-once)")
	fl.StringVar(&note, "note", "", "free-text note stored with the certificate")
