func newCertDeleteCmd() *cobra.Command {
	var yes bool
	cmd := &cobra.Command{
		Use:     "delete <id|serial>",
		Aliases: []string{"rm"},
		Short:   "Delete a certificate record",
		Args:    cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx, cancel := cmdContext(cmd)
			defer cancel()
			if !yes {
				if !termio.Interactive() {
					return fmt.Errorf("refusing to delete %q non-interactively; pass --yes", args[0])
				}
				if !termio.AskYesNo(fmt.Sprintf("Delete the record for %q?", args[0]), false) {
					return nil
				}
			}
			c, err := client()
			if err != nil {
				return err
			}
			if err := c.DeleteCert(ctx, args[0]); err != nil {
				return err
			}
			termio.OK("deleted %s", args[0])
			return nil
		},
	}
	cmd.Flags().BoolVar(&yes, "yes", false, "do not ask for confirmation")
	return cmd
}
