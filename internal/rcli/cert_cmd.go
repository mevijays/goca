func newCertHistoryCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "history <id|serial>",
		Short: "Walk a certificate's rotation chain",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx, cancel := cmdContext(cmd)
			defer cancel()
			c, err := client()
			if err != nil {
				return err
			}
			res, err := c.CertHistory(ctx, args[0])
			if err != nil {
				return err
			}
			if flagJSON {
				return termio.PrintRaw(res.Raw)
			}
			chain := res.Value.History
			// The header names the certificate that was asked about, which is
			// the entry the server marked as current.
			subject := args[0]
			for i := range chain {
				if chain[i].ID == res.Value.CurrentID {
					subject = chain[i].CommonName
				}
			}
			termio.Section(fmt.Sprintf("Rotation history for %s", subject))
			t := termio.NewTable("", "id", "serial", "issued", "expires", "status", "key")
			for _, h := range chain {
				marker := " "
				if h.ID == res.Value.CurrentID {
					marker = "→"
				}
				key := "-"
				if h.HasKey {
					key = "stored"
				}
				t.Row(marker, h.ID, h.SerialHex, h.CreatedAt.Format("2006-01-02"),
					h.NotAfter.Format("2006-01-02"), h.EffectiveStatus(), key)
			}
			t.Flush()
			if len(chain) == 1 {
				fmt.Println()
				termio.Info("this certificate has not been renewed")
			}
			return nil
		},
	}
}

func newCertRevokeCmd() *cobra.Command {
	var reason string
	cmd := &cobra.Command{
		Use:   "revoke <id|serial>",
		Short: "Revoke a certificate",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx, cancel := cmdContext(cmd)
			defer cancel()
			// Parsed here rather than server-side so that --reason takes the same
			// names as `goca cert revoke` does; pki.ParseReason accepts the numeric
			// codes too, so scripts passing "4" keep working either way.
			code, err := pki.ParseReason(reason)
			if err != nil {
				return err
			}
			c, err := client()
			if err != nil {
				return err
			}
			if err := c.RevokeCert(ctx, args[0], code); err != nil {
				return err
			}
			termio.OK("revoked %s (reason: %s)", args[0], pki.ReasonName(code))
			return nil
		},
	}
	cmd.Flags().StringVar(&reason, "reason", "unspecified", "RFC 5280 revocation reason")
	return cmd
}

